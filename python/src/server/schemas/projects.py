"""
Project Schemas for API Requests and Responses
"""

from datetime import datetime
from typing import Any

from pydantic import BaseModel, Field

from src.server.services.shared_constants import DEFAULT_ASSIGNEE


class CreateProjectRequest(BaseModel):
    title: str
    description: str | None = None
    github_repo: str | None = None
    docs: list[Any] | None = None
    features: list[Any] | None = None
    data: list[Any] | None = None
    technical_sources: list[str] | None = None
    business_sources: list[str] | None = None
    pinned: bool | None = None


class UpdateProjectRequest(BaseModel):
    title: str | None = None
    description: str | None = None
    github_repo: str | None = None
    docs: list[Any] | None = None
    features: list[Any] | None = None
    data: list[Any] | None = None
    technical_sources: list[str] | None = None
    business_sources: list[str] | None = None
    pinned: bool | None = None


class AssignableUser(BaseModel):
    id: str
    name: str
    role: str


class CreateTaskRequest(BaseModel):
    project_id: str
    title: str
    description: str | None = None
    status: str | None = "todo"
    priority: str | None = "medium"
    assignee: str | None = DEFAULT_ASSIGNEE
    assignee_id: str | None = None
    task_order: int | None = 0
    feature: str | None = None
    due_date: datetime | None = None
    knowledge_source_ids: list[str] | None = None
    is_recurring: bool | None = False
    crawler_target_id: str | None = None
    schedule_config: dict[str, Any] | None = None


class RefineTaskRequest(BaseModel):
    title: str
    description: str


class RefineTaskResponse(BaseModel):
    refined_description: str = Field(description="Refined task description generated by AI")


class Attachment(BaseModel):
    filename: str
    url: str


class TaskDetails(BaseModel):
    id: str | None = Field(default=None, description="Task ID")
    project_id: str | None = Field(default=None, description="Project ID")
    title: str | None = Field(default=None, description="Task title")
    description: str | None = Field(default=None, description="Task description")
    status: str | None = Field(default=None, description="Task status")
    assignee: str | None = Field(default=None, description="Assignee name")
    assignee_id: str | None = Field(default=None, description="Assignee user/agent ID")
    collaborator_agent_ids: list[str] | None = Field(default_factory=list, description="Collaborator agent IDs")
    task_order: int | None = Field(default=0, description="Task order")
    priority: str | None = Field(default=None, description="Task priority")
    feature: str | None = Field(default=None, description="Task feature")
    created_at: str | datetime | None = Field(default=None, description="Creation timestamp")
    updated_at: str | datetime | None = Field(default=None, description="Update timestamp")
    due_date: str | datetime | None = Field(default=None, description="Due date")
    is_recurring: bool | None = Field(default=False, description="Is recurring task")
    crawler_target_id: str | None = Field(default=None, description="Crawler target ID")
    schedule_config: dict[str, Any] | None = Field(default=None, description="Schedule configuration")
    knowledge_source_ids: list[str] | None = Field(default_factory=list, description="Knowledge source IDs")
    attachments: list[Attachment] | None = Field(default_factory=list, description="Attachments")
    output: dict[str, Any] | str | None = Field(default=None, description="Agent execution output")
    retry_count: int | None = Field(default=0, description="Retry count")


class GenerateTaskFromAlertRequest(BaseModel):
    alert_id: str
    assignee_id: str | None = None


class GenerateTaskFromAlertResponse(BaseModel):
    task: TaskDetails | None = Field(default=None, description="The newly created task details")
    message: str | None = Field(default=None, description="Response status message")
    error: str | None = Field(default=None, description="Error message if task generation failed")


class UpdateTaskRequest(BaseModel):
    title: str | None = None
    description: str | None = None
    status: str | None = None
    priority: str | None = None
    assignee: str | None = None
    assignee_id: str | None = None
    collaborator_agent_ids: list[str] | None = None
    task_order: int | None = None
    feature: str | None = None
    attachments: list[Attachment] | None = None
    retry_count: int | None = None
    due_date: datetime | None = None
    is_recurring: bool | None = None
    crawler_target_id: str | None = None
    schedule_config: dict[str, Any] | None = None


class AgentStatusUpdateRequest(BaseModel):
    status: str
    agent_id: str


class AgentOutputUpdateRequest(BaseModel):
    output: dict[str, Any]
    agent_id: str


class AgentCallbackResponse(BaseModel):
    task: dict[str, Any] | None = None
    message: str | None = None


class TaskListPagination(BaseModel):
    total: int = Field(description="Total count of tasks")
    page: int = Field(description="Current page number")
    per_page: int = Field(description="Tasks per page")
    pages: int = Field(description="Total number of pages")


class TaskListResponse(BaseModel):
    tasks: list[TaskDetails] = Field(default_factory=list, description="List of tasks")
    pagination: TaskListPagination = Field(description="Pagination details")


class UpdateTaskResponse(BaseModel):
    message: str = Field(description="Status message")
    task: TaskDetails | None = Field(default=None, description="Updated task details")


class ArchiveTaskResponse(BaseModel):
    message: str = Field(description="Status message")


class CreateTaskResponse(BaseModel):
    message: str = Field(description="Status message")
    task: TaskDetails | None = Field(default=None, description="Created task details")


class DocumentStats(BaseModel):
    version_count: int | None = Field(default=None, description="Document version count")
    content_size: int | None = Field(default=None, description="Document content size in bytes")


class DocumentItemResponse(BaseModel):
    id: str | None = Field(default=None, description="Document ID")
    type: str | None = Field(default=None, description="Document type")
    title: str | None = Field(default=None, description="Document title")
    content: dict[str, Any] | None = Field(default=None, description="Document content dictionary")
    author: str | None = Field(default=None, description="Document author")
    tags: list[str] | None = Field(default_factory=list, description="Document tags")
    created_at: str | datetime | None = Field(default=None, description="Creation timestamp")
    updated_at: str | datetime | None = Field(default=None, description="Last update timestamp")
    version: int | None = Field(default=1, description="Document version number")
    stats: DocumentStats | None = Field(default=None, description="Document statistics")


class DocumentListResponse(BaseModel):
    documents: list[DocumentItemResponse] = Field(default_factory=list, description="List of project documents")


class CreateDocumentResponse(BaseModel):
    message: str = Field(description="Status message")
    document: DocumentItemResponse | None = Field(default=None, description="Created document details")


class CreateDocumentRequest(BaseModel):
    document_type: str
    title: str
    content: dict[str, Any] | None = None
    tags: list[str] | None = None
    author: str | None = None


class UpdateDocumentRequest(BaseModel):
    title: str | None = None
    content: dict[str, Any] | None = None
    tags: list[str] | None = None
    author: str | None = None


class CreateVersionRequest(BaseModel):
    field_name: str
    content: dict[str, Any]
    change_summary: str | None = None
    change_type: str | None = "update"
    document_id: str | None = None
    created_by: str | None = "system"


class RestoreVersionRequest(BaseModel):
    restored_by: str | None = "system"


class CreateProjectResponse(BaseModel):
    project_id: str | None = Field(default=None, description="The ID of the created project")
    project: dict[str, Any] | None = Field(default=None, description="The created project details")
    status: str = Field(default="completed", description="Status of project creation")
    message: str = Field(description="Response status message")


class DeleteProjectResponse(BaseModel):
    message: str = Field(description="Status message")
    deleted_tasks: int = Field(default=0, description="Number of tasks deleted with the project")


class ProjectListResponse(BaseModel):
    projects: list[dict[str, Any]] = Field(description="List of scoped projects")
    timestamp: str = Field(description="ISO timestamp of response generation")
    count: int = Field(description="Total count of projects returned")


class VersionListResponse(BaseModel):
    versions: list[dict[str, Any]] = Field(description="List of document versions")
    total_count: int = Field(description="Total number of versions")


class CreateVersionResponse(BaseModel):
    message: str = Field(description="Status message")
    version: dict[str, Any] | None = Field(default=None, description="Created version object")


class RestoreVersionResponse(BaseModel):
    message: str = Field(description="Status message")
    restored_content: dict[str, Any] | None = Field(default=None, description="Restored content")


class ProjectDetailResponse(BaseModel):
    id: str | None = Field(default=None, description="Project ID")
    title: str | None = Field(default="", description="Project title")
    description: str | None = Field(default="", description="Project description")
    github_repo: str | None = Field(default=None, description="GitHub repository URL")
    department: str | None = Field(default=None, description="Department owner")
    status: str | None = Field(default="planning", description="Project status")
    docs: list[Any] | dict[str, Any] | None = Field(default=None, description="Project documents")
    features: list[Any] | None = Field(default=None, description="Project features")
    data: dict[str, Any] | list[Any] | None = Field(default=None, description="Project metadata or data")
    pinned: bool | None = Field(default=False, description="Whether project is pinned")
    stats: dict[str, Any] | None = Field(default=None, description="Project stats")
    technical_sources: list[str] | None = Field(default=None, description="Technical sources")
    business_sources: list[str] | None = Field(default=None, description="Business sources")
    created_at: str | datetime | None = Field(default=None, description="Creation timestamp")
    updated_at: str | datetime | None = Field(default=None, description="Last update timestamp")
